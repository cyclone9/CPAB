// Writes the public lists repository (cyclone9/CPAB-Lists) into a folder. Usage: npm run export-lists -- <target>
// Every source list goes in sources/<name>/ as a byte-identical copy of its snapshot, with its record and,
// where the licence asks for one, the licence text. Each run replaces sources/ and the files below, so git
// in the target shows exactly what changed; nothing else in the target (its .git/, for one) is touched.
// It reads only local files and makes no request.
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, realpathSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { LISTS } from './lists.config.js';
import { listLines, snapshotParts } from './notices.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export const GENERATED_MARK = '<!-- Generated by scripts/export-lists.js in the CPAB repository. Edit the list records there, not this file. -->';
const TOP_FILES = ['README.md', 'README.fa.md', 'LICENSE', 'SOURCES.md', 'cpab-own.txt', 'cpab-exceptions.txt'];
const OWN_FILES = ['cpab-own.txt', 'cpab-exceptions.txt'];

// The same test as the CPAB repository's guard, plus what must never appear in text CPAB writes.
const EMAIL = /[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}/;

class ExportError extends Error {}
const fail = (message) => { throw new ExportError(message); };

const sha256 = (buffer) => createHash('sha256').update(buffer).digest('hex');

// The target as it will be on disk, with symlinks in the part that exists already resolved.
function realTarget(target) {
  let existing = resolve(target);
  const rest = [];
  while (!existsSync(existing)) {
    rest.unshift(basename(existing));
    existing = dirname(existing);
  }
  return join(realpathSync(existing), ...rest);
}

function checkTarget(target, repoRoot) {
  const real = realTarget(target);
  // Local tooling and private files live in hidden folders, so an export never goes into one.
  if ([resolve(target), real].some((path) => path.split(sep).some((part) => part.length > 1 && part.startsWith('.')))) fail(`refusing ${target}: it is inside a hidden folder`);
  const repo = realpathSync(repoRoot);
  if (real === repo || real.startsWith(repo + sep)) fail(`refusing ${target}: it is inside the CPAB repository (${repo})`);
  if (!existsSync(real)) return real;
  if (!statSync(real).isDirectory()) fail(`refusing ${target}: it is not a folder`);
  // Only an earlier export or an empty folder (a fresh clone has only .git/), so sources/ in someone
  // else's folder is never removed.
  const sources = join(real, 'SOURCES.md');
  const ours = existsSync(sources) && readFileSync(sources, 'utf8').includes(GENERATED_MARK);
  const others = readdirSync(real).filter((name) => name !== '.git');
  if (!ours && others.length) fail(`refusing ${target}: the folder holds other files and no SOURCES.md from an earlier export`);
  return real;
}

function licenceFile(meta, { repoRoot, listsDir }) {
  const { spdx, copy } = meta.licence;
  if (/^CC-BY(-SA)?-\d/.test(spdx)) return null;
  if (/^AGPL-3\.0-(only|or-later)$/.test(spdx)) {
    return { path: join(listsDir, copy ?? 'LICENSE.AGPL-3.0.txt'), mark: 'GNU AFFERO GENERAL PUBLIC LICENSE' };
  }
  if (/^GPL-3\.0-(only|or-later)$/.test(spdx)) return { path: join(repoRoot, 'LICENSE'), mark: 'GNU GENERAL PUBLIC LICENSE' };
  return fail(`${meta.name}: no rule for licence ${spdx}, so the export can't tell whether its text must go with it`);
}

// What CPAB changed, from how the list is fetched (scripts/update-lists.js).
function changesNote(list) {
  if (!list.repository) return 'unmodified snapshot';
  const names = list.repository.files.map(({ name }) => `\`${name}\``).join(', ');
  const hosts = list.repository.files.filter(({ format }) => format === 'hosts').map(({ name }) => `\`${name}\``);
  return `the files ${names}, taken at the recorded commit and joined in that order, each under a \`! ==== <file> ====\` line`
    + (hosts.length ? `; ${hosts.join(', ')} rewritten from host-file lines to \`||domain^\` rules` : '');
}

function sourceEntry({ list, meta, hash, licence }) {
  const folder = `sources/${list.name}/`;
  const lines = [
    ...listLines(meta, 'Licence'),
    `- **Folder:** \`${folder}\`, with the snapshot \`${folder}${list.name}.txt\` and its record \`${folder}meta.json\``,
    `- **Licence text:** ${licence ? `\`${folder}LICENSE.txt\`` : meta.licence.url}`,
    `- **Snapshot:** ${snapshotParts(meta.snapshot).filter(Boolean).join(', ')}`,
    `- **SHA-256:** \`${hash}\``,
    `- **Changes:** ${changesNote(list)}`,
  ];
  if (meta.snapshot.files) lines.push(`- **Parts:** ${meta.snapshot.files.map(({ name, sha256: part }) => `\`${name}\` (SHA-256 \`${part}\`)`).join(', ')}`);
  return lines.join('\n');
}

function sourcesText(entries) {
  return [
    '<!-- SPDX-License-Identifier: GPL-3.0-or-later -->',
    GENERATED_MARK,
    '# Sources',
    '',
    'Each list below is someone else\'s work, kept as its own file under `sources/<name>/` and never merged with another list. It keeps its own licence and its authors\' credit. A snapshot is the file as fetched, with LF line endings; the Changes line says where CPAB changed more than that.',
    '',
    'CPAB\'s own files, `cpab-own.txt` and `cpab-exceptions.txt`, are under GPL-3.0-or-later (`LICENSE`).',
    '',
    entries.map(sourceEntry).join('\n\n'),
    '',
  ].join('\n');
}

// Reads and checks everything before the target is touched, so a failed run leaves it as it was.
function collect({ repoRoot, listsDir, readmeDir }) {
  const readmes = ['README.md', 'README.fa.md'].map((name) => {
    const path = join(readmeDir, name);
    if (!existsSync(path)) fail(`${relative(repoRoot, path) || path} is missing: the lists repository's README comes from there`);
    return { name, path };
  });
  const entries = LISTS.filter((list) => !list.ownFormat).map((list) => {
    const metaPath = join(listsDir, list.metaFile);
    const snapshotPath = join(listsDir, list.listFile);
    if (!existsSync(metaPath)) fail(`${list.name}: its record ${list.metaFile} is missing`);
    if (!existsSync(snapshotPath)) fail(`${list.name}: its snapshot ${list.listFile} is missing`);
    const meta = JSON.parse(readFileSync(metaPath, 'utf8'));
    if (!meta.licence?.spdx || !meta.licence?.name || !meta.licence?.url) fail(`${list.name}: ${list.metaFile} names no licence with its SPDX identifier and URL`);
    const hash = sha256(readFileSync(snapshotPath));
    if (meta.snapshot?.sha256 && meta.snapshot.sha256 !== hash) fail(`${list.name}: ${list.listFile} doesn't match the SHA-256 in ${list.metaFile}`);
    const licence = licenceFile(meta, { repoRoot, listsDir });
    if (licence && !readFileSync(licence.path, 'utf8').includes(licence.mark)) fail(`${licence.path} is not the ${licence.mark} text`);
    return { list, meta, metaPath, snapshotPath, hash, licence };
  });
  const own = OWN_FILES.map((name) => {
    const path = join(listsDir, name);
    if (!existsSync(path)) fail(`${name} is missing from the lists folder`);
    return { name, path };
  });
  return { readmes, entries, own };
}

function checkText(name, text, authored) {
  if (authored && EMAIL.test(text)) fail(`${name} holds an email address`);
}

export function exportLists(target, { repoRoot = root, listsDir = join(repoRoot, 'lists'), readmeDir = join(repoRoot, 'scripts', 'lists-repo') } = {}) {
  if (!target) fail('usage: npm run export-lists -- <target folder>');
  const real = checkTarget(target, repoRoot);
  const { readmes, entries, own } = collect({ repoRoot, listsDir, readmeDir });
  const sources = sourcesText(entries);

  for (const { name, path } of [...readmes, ...own]) checkText(name, readFileSync(path, 'utf8'), true);
  for (const { list, metaPath, snapshotPath } of entries) {
    checkText(list.metaFile, readFileSync(metaPath, 'utf8'), true);
    checkText(list.listFile, readFileSync(snapshotPath, 'utf8'), false);
  }
  checkText('SOURCES.md', sources, true);

  mkdirSync(real, { recursive: true });
  rmSync(join(real, 'sources'), { recursive: true, force: true });
  for (const name of TOP_FILES) rmSync(join(real, name), { force: true });

  for (const { name, path } of [...readmes, ...own]) copyFileSync(path, join(real, name));
  copyFileSync(join(repoRoot, 'LICENSE'), join(real, 'LICENSE'));
  writeFileSync(join(real, 'SOURCES.md'), sources);
  for (const { list, metaPath, snapshotPath, licence } of entries) {
    const folder = join(real, 'sources', list.name);
    mkdirSync(folder, { recursive: true });
    copyFileSync(snapshotPath, join(folder, `${list.name}.txt`));
    copyFileSync(metaPath, join(folder, 'meta.json'));
    if (licence) copyFileSync(licence.path, join(folder, 'LICENSE.txt'));
  }
  return { target: real, lists: entries.map(({ list }) => list.name) };
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  try {
    const { target, lists } = exportLists(process.argv[2]);
    console.log(`Wrote ${lists.length} lists to ${target}: ${lists.join(', ')}`);
  } catch (error) {
    if (!(error instanceof ExportError)) throw error;
    console.error(`export-lists: ${error.message}`);
    process.exitCode = 1;
  }
}
